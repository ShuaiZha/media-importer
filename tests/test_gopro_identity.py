"""Reboot timestamp regression, with kilobyte media and disposable storage."""
import copy
import tempfile
import threading
import unittest
from pathlib import Path
from urllib.parse import parse_qs, unquote, urlsplit

from media_importer.adapters.gopro import GoProSource, make_asset
from media_importer.adapters.gopro_models import compatibility
from media_importer.model import SourceError
from media_importer.service import Service
from media_importer.store import Store
import test_gopro
from test_service import FakeDestination, configuration


class RebootCamera(GoProSource):
    """Exercise actual parsing, inventory, verification and download code."""
    def __init__(self, config):
        super().__init__(config)
        self.device_name = 'HERO9 Black'
        self.compatibility = compatibility(self.device_name)
        body, self.metadata = test_gopro.GoProTests.mp4_fixture()
        self.video = '100GOPRO/GH010001.MP4'
        self.preview = '100GOPRO/GL010001.LRV'
        self.files = {self.video: body, self.preview: b'preview'}
        self.created_shift = 0
        self.modified = 'Tue, 14 Nov 2023 22:13:20 GMT'
        self.downloads = []
        self.ranges = []

    def identify(self):
        return {'serial_number': self.serial, 'model_name': self.device_name}

    def ensure_idle(self):
        pass

    def keep_alive(self):
        pass

    def fork(self, stop=None, **kwargs):
        client = copy.copy(self)
        client.stop = stop
        return client

    def telemetry(self):
        return {'available': False}

    def paths(self):
        return set(self.files)

    def _json(self, path):
        metadata = {**self.metadata, 'cre': str(int(self.metadata['cre']) + self.created_shift)}
        if path == '/gopro/media/list':
            return {'media': [{'d': '100GOPRO', 'fs': [{'n': 'GH010001.MP4', **metadata}]}]}
        if path.startswith('/gopro/media/info?'):
            assert parse_qs(urlsplit(path).query)['path'] == [self.video]
            return metadata
        raise AssertionError('Unexpected camera request: ' + path)

    def _open(self, url, headers=None):
        assert url.startswith('/videos/DCIM/'), url  # No deletion/control endpoints.
        path = unquote(url[len('/videos/DCIM/'):])
        body = self.files[path]
        response = {'Last-Modified': self.modified, 'Content-Length': str(len(body))}
        if headers and 'Range' in headers:
            first, last = map(int, headers['Range'][6:].split('-'))
            self.ranges.append((path, first, last))
            response['Content-Range'] = f'bytes {first}-{last}/{len(body)}'
            return test_gopro.Response(body[first:last + 1], 206, response)
        self.downloads.append(path)
        return test_gopro.Response(body, 200, response)


class GoProIdentityTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.config = configuration(archive_previews=False)
        self.camera = RebootCamera(self.config)
        self.remote = FakeDestination()
        self.directory = Path(self.temp.name) / 'data'
        self.store = Store.create(self.directory)
        self.addCleanup(lambda: self.store.close())

    def service(self):
        return Service(self.config, self.store, self.camera, self.remote, threading.Event())

    def test_reboot_changes_only_api_time_preserving_existing_video_and_preview_ids(self):
        before = self.camera.snapshot()
        for shift in (-32, 3600, -86400):
            self.camera.created_shift = shift
            self.assertEqual(before, self.camera.snapshot())
        # This is also the identity generated by the old version before reboot.
        for asset in before:
            self.assertEqual(asset.identity, make_asset(asset.serial, asset.path, asset.size,
                self.camera.metadata['cre'], asset.modified, asset.metadata['gumi'],
                asset.metadata['primary'], asset.metadata['parent_gumi']).identity)
        self.assertFalse(self.camera.downloads)
        self.assertTrue(all(end < 20 or start >= 1044 for path, start, end in self.camera.ranges
                            if path == self.camera.video))  # Never read mdat for metadata.

    def test_reboot_during_download_verification_preserves_identity(self):
        asset = next(a for a in self.camera.snapshot() if a.path == self.camera.video)
        self.camera.created_shift = -32
        self.camera.download(asset, Path(self.temp.name) / 'video.download', lambda *_: None)
        self.assertEqual([self.camera.video], self.camera.downloads)
        self.assertEqual(self.camera.files[asset.path], (Path(self.temp.name) / 'video.download').read_bytes())

    def test_settled_legacy_index_and_restart_do_not_reimport_or_rename(self):
        self.assertTrue(self.service().cycle()['complete'])
        self.assertEqual(2, self.service().settle())
        before = [dict(r) for r in self.store.db.execute('SELECT * FROM source_index ORDER BY asset_id')]
        archives = copy.deepcopy(self.remote.objects)
        self.store.close()
        self.store = Store.create(self.directory)
        self.camera.created_shift = -32
        self.service().cycle()
        self.assertFalse(self.store.files())
        self.assertEqual(before, [dict(r) for r in self.store.db.execute('SELECT * FROM source_index ORDER BY asset_id')])
        self.assertEqual(archives, self.remote.objects)
        self.assertEqual([self.camera.video], self.camera.downloads)
        self.assertEqual(1, len(self.remote.uploads))

    def test_pending_tasks_and_complete_cache_keep_their_ids_and_contents(self):
        service = self.service()
        service.prepare_imports()
        row = next(r for r in service.rows() if r['state'] == 'pending')
        service.allocate(row)  # Retain the assigned archive name as well.
        before = self.store.files()
        self.camera.created_shift = -32
        service.prepare_imports()
        self.assertEqual(before, self.store.files())
        service.import_asset(self.store.get(row['id']))
        cached = self.store.get(row['id'])
        content = self.store.cached_path(cached).read_bytes()
        self.store.close()
        self.store = Store.create(self.directory)
        self.camera.created_shift = 3600
        self.service().prepare_imports()
        self.assertEqual(cached, self.store.get(row['id']))
        self.assertEqual(content, self.store.cached_path(cached).read_bytes())
        self.assertTrue(self.service().cycle()['complete'])
        self.assertEqual([self.camera.video], self.camera.downloads)
        self.assertEqual(1, len(self.remote.uploads))

    def test_same_path_size_and_api_timestamp_cannot_hide_new_material(self):
        before = self.camera.snapshot()
        self.service().cycle()
        self.service().settle()
        old = bytes.fromhex(self.camera.metadata['gumi'])
        new = bytes.fromhex('f' * 32)
        self.camera.files[self.camera.video] = self.camera.files[self.camera.video].replace(old, new)
        self.camera.metadata['gumi'] = new.hex()
        after = self.camera.snapshot()
        self.assertTrue(all(a.identity != b.identity for a, b in zip(before, after)))
        self.assertTrue(self.service().cycle()['complete'])
        self.assertEqual(2, len(self.remote.uploads))
        names = {r['remote_path'] for r in self.store.files() if r['state'] == 'uploaded'}
        self.assertTrue(any(name.endswith('GH010001_1.MP4') for name in names))

    def test_header_time_change_is_not_normalized_away(self):
        before = self.camera.snapshot()
        stamp = int(self.camera.metadata['cre']) + 2082844800
        self.camera.files[self.camera.video] = self.camera.files[self.camera.video].replace(
            stamp.to_bytes(4, 'big'), (stamp + 100).to_bytes(4, 'big'))
        after = self.camera.snapshot()
        self.assertTrue(all(a.identity != b.identity for a, b in zip(before, after)))
        with self.assertRaises(SourceError):
            self.camera.verify_primary(next(a for a in before if a.metadata['primary']))

    def test_gumi_disagreement_or_missing_metadata_never_falls_back_to_api_time(self):
        for gumi in ('f' * 32, '', '0' * 32):
            with self.subTest(gumi=gumi):
                self.camera.metadata['gumi'] = gumi
                with self.assertRaises(SourceError):
                    self.camera.snapshot()

    def test_unverified_models_keep_existing_metadata_behavior(self):
        self.camera.compatibility = compatibility('HERO13 Black')
        before = self.camera.snapshot()
        self.camera.created_shift = -32
        after = self.camera.snapshot()
        self.assertTrue(all(a.identity != b.identity for a, b in zip(before, after)))
        self.assertTrue(all((start, end) == (0, 0) for _, start, end in self.camera.ranges))
